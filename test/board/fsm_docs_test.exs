defmodule Board.FsmDocsTest do
  use ExUnit.Case, async: true

  test "diagram uses named group rows once and leaves group stays to the matrix" do
    text = Board.Stage.to_mermaid()
    assert text =~ "stateDiagram-v2\n    [*] --> queued\n"
    assert text =~ "working --> building: progress / append(progress), emit(stage)"
    assert text =~ ~s(state "working: dispatched, building" as working)
    refute text =~ "after_report --> after_report"
  end

  test "matrix includes guarded fallbacks and ordered entry effects" do
    text = Board.Stage.matrix()

    assert text =~
             "| building | dispatch [new_session?] | -> dispatched | record(session), append(redispatched), emit(stage) |"

    assert text =~ "| building | dispatch | invalid |  |"

    assert text =~
             "| pr_open | cr_merged | -> merged | record(merge), emit(stage), suggest(close_bead) |"

    assert text =~ "| abandoned | cr_merged | ignored |  |"
    assert length(String.split(String.trim(text), "\n")) == 135
  end

  for {name, module} <- [
        {"stage", Board.Stage},
        {"delivery_machine", Board.DeliveryMachine},
        {"spool_machine", Board.SpoolMachine},
        {"epic", Board.Epic},
        {"disclosure", Board.Initiatives.Disclosure},
        {"ticket_sheet", Board.TicketSheet},
        {"reload_machine", Board.Config.ReloadMachine},
        {"read_machine", Board.Beads.ReadMachine},
        {"read_lifecycle", Board.Forge.ReadLifecycle},
        {"refresh_status", Board.Forge.RefreshStatus},
        {"action", Board.Merge.Action},
        {"schedule_machine", Board.Beads.ScheduleMachine},
        {"sync_machine", Board.Beads.SyncMachine},
        {"watch_machine", Board.Config.WatchMachine}
      ] do
    test "#{name} documentation matches the committed golden" do
      module = unquote(module)

      rendered =
        "# #{unquote(name)}\n\nGenerated by `mix board.fsm.docs`. Do not edit by hand.\n\n```mermaid\n" <>
          module.to_mermaid() <> "```\n\n" <> module.matrix()

      assert File.read!("docs/machines/#{unquote(name)}.md") == rendered
    end
  end
end
