// NODE_PATH=<Playwright node_modules> node tools/filters-acceptance.cjs
// Uses an already populated, web-only server; no database or beads writes.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.BOARD_URL || 'http://127.0.0.1:4754';
  const out = process.env.BOARD_SCREENSHOT_DIR || 'docs/acceptance/bb-filters';
  fs.mkdirSync(out, {recursive: true});
  const ready = () => page.locator('[data-phx-main].phx-connected').waitFor();
  const selected = () => page.locator('#sidebar-project-beads-board.bb-nav-active[aria-current="true"]').waitFor();
  await page.goto(base + '/?project=');
  await ready();
  const count = await page.locator('#sidebar-project-beads-board').innerText();
  await page.locator('#sidebar-project-beads-board').click();
  await selected();
  await page.waitForURL(url => url.searchParams.get('project') === 'beads-board');
  assert.equal(await page.locator('#sidebar-project-beads-board').innerText(), count);
  await page.click('#toggle-filters');
  await page.locator('#toggle-filters[aria-expanded=true]').waitFor();
  await page.selectOption('#filters_status', 'open');
  await page.fill('#filters_q', 'board');
  await page.waitForURL(url => url.searchParams.get('q') === 'board');
  const filtered = page.url();
  await page.getByRole('link', {name: 'Settings', exact: true}).click();
  await page.locator('#config-status').waitFor();
  await page.getByRole('link', {name: 'Initiatives', exact: true}).click();
  await selected();
  await page.waitForURL(filtered);
  assert.equal(await page.inputValue('#filters_q'), 'board');
  await page.reload();
  await ready();
  await selected();
  assert.equal(await page.locator('#epics [data-kind="epic"]').count(), 1);
  assert.equal(await page.locator('#epics [data-bead="bb-c2w"]').count(), 1);
  for (const theme of ['light', 'dark']) {
    await page.click('#theme-' + theme);
    await page.screenshot({path: `${out}/initiatives-${theme}.png`, fullPage: true, animations: 'disabled'});
  }
  await page.locator('#sidebar-project-beads-board').click();
  await page.waitForURL(url => url.searchParams.get('project') === '');
  assert.equal(await page.locator('#sidebar-project-beads-board.bb-nav-active').count(), 0);
  assert.equal(await page.inputValue('#filters_q'), 'board');
  await page.goBack();
  await selected();
  await page.goForward();
  await page.waitForURL(url => url.searchParams.get('project') === '');
  await page.goto(base + '/?project=form-engine');
  await ready();
  await page.locator('#sidebar-project-form-engine.bb-nav-active').waitFor();
  assert.equal(await page.inputValue('#filters_q'), '');
  await page.goto(base + '/');
  await ready();
  await page.locator('#sidebar-project-form-engine.bb-nav-active').waitFor();
  await page.waitForURL(url => url.searchParams.get('project') === 'form-engine');
  await page.evaluate(() => localStorage.setItem('board:initiative-filters:v1', 'broken json'));
  await page.goto(base + '/');
  await ready();
  assert.equal(await page.locator('[id^="sidebar-project-"].bb-nav-active').count(), 0);
  await page.goto(base + '/?project[]=bad&status=invalid&q[]=bad');
  await ready();
  assert.equal(await page.locator('[id^="sidebar-project-"].bb-nav-active').count(), 0);
  assert.equal(await page.inputValue('#filters_q'), '');
  await page.goto(base + '/?project=beads-board');
  await ready();
  await selected();
  const other = await browser.newContext();
  const otherPage = await other.newPage();
  await otherPage.goto(base + '/');
  await otherPage.locator('[data-phx-main].phx-connected').waitFor();
  assert.equal(await otherPage.locator('[id^="sidebar-project-"].bb-nav-active').count(), 0);
  await other.close();
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: sidebar set/clear/counts, Settings round-trip, reload, URL authority, back/forward, bare-route restore, corrupt storage, malformed params, browser isolation, light/dark screenshots; no page errors');
})().catch(error => { console.error(error); process.exit(1); });
